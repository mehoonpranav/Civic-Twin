export function citiesForState(state: string) {
  return INDIAN_STATES.find((s) => s.name === state)?.cities ?? [];
}

export function isKnownState(state: string) {
  return INDIAN_STATES.some((s) => s.name === state);
}

export function isKnownCity(state: string, city: string) {
  return citiesForState(state).includes(city);
}

